    /// <summary>
    /// 지금 상황에 맞는 대사 한 줄. <paramref name="role"/> 이 범위를 벗어나면 돌려 쓴다 —
    /// 곰을 네 마리로 늘려도 안 터진다.
    /// </summary>
    public static string Random(int role)
    {
        bool saved = GalleryLights.AllCollected;

        // 음수도 접어 넣는다. 한 줄로 쓰면 `% Roles switch` 를 «Roles switch 의 결과로 나눈다» 로
        // 읽어서 컴파일이 안 된다 — 변수로 끊는다.
        int r = ((role % Roles) + Roles) % Roles;

        string[] pool = r switch
        {
            0 => saved ? PlumberSaved : Plumber,
            1 => saved ? StudentSaved : Student,
            _ => saved ? ElderSaved : Elder,
        };

        return pool[UnityEngine.Random.Range(0, pool.Length)];
    }

