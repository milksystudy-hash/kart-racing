    /// <b>따옴표 안만 채우면 화면에 바로 뜬다</b> — 다른 건 아무것도 안 해도 돼.
    ///
    /// ── 쓸 때 ──────────────────────────────────────────────────────────
    /// · <b>비워 두면 그 줄을 아예 안 그린다.</b> 아홉 개를 한꺼번에 채울 필요 없어.
