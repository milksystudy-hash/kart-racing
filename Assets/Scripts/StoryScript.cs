    public static bool TryFind(string sceneId, out Scene scene)
    {
        for (int i = 0; i < All.Length; i++)
            if (All[i].id == sceneId) { scene = All[i]; return true; }

        scene = default;
        return false;
    }

    /// <summary>조건을 통과한 줄만 골라서 순서대로 돌려준다. 이야기가 갈리는 건 여기서 일어난다.</summary>
    public static List<DialogueLine> Playable(string sceneId)
    {
        var result = new List<DialogueLine>();
        if (!TryFind(sceneId, out var scene) || scene.lines == null) return result;

        foreach (var line in scene.lines)
            if (line.Passes) result.Add(line);

        return result;
    }

    public static string TitleOf(string sceneId) =>
        TryFind(sceneId, out var scene) ? scene.title : sceneId;

    /// <summary>
    /// 지금 진행 중인 장에 맞는 이야기 장면. 임무 판정이 붙으면
    /// "필수 임무 성공 → 이 장면 재생 → StoryProgress.AdvanceChapter()" 로 이어진다.
    /// </summary>
    public static string SceneForChapter(int chapter) => chapter switch
    {
        0 => "prologue",
        1 => "ch1",
        2 => "ch2",
        3 => "ch3",
        // ★★ 2026-10-01 유저: *"수집품 7개인데 T 를 누르면 처음 대화가 나온다."*
        //   <b>4장에 걸린 장면이 «epilogue» 뿐이었다.</b> 그런데 에필로그는 결승을 깨야
        //   나오는 것이라 아래 <see cref="CurrentScene"/> 가 빈 문자열로 막았고,
        //   그러면 T 는 «고를 게 없다» 며 프롤로그로 떨어진다 — 그게 «처음 대화» 다.
        //   <b>7~8개 구간에도 제 장면이 있어야 한다.</b> 에필로그는 결승 뒤에만.
        4 => "ch4",
        _ => "epilogue",
    };

    /// <summary>
    /// ★★ <b>지금 틀어야 할 장면.</b> 장 번호만으로는 결말이 어긋난다 — 2026-09-21 에
    /// 구멍 둘을 찾아서 여기로 모았다.
    ///
    /// <b>구멍 1 — 결승 장면이 영영 안 나왔다.</b> <c>final_before</c>/<c>final_after</c> 가
    /// 표에는 있는데 <see cref="SceneForChapter"/> 에 없어서 <b>아무 데서도 안 불렸다.</b>
    ///
    /// <b>구멍 2 — 에필로그가 7판 뒤에 떴다.</b> 수집품 <c>recorder</c>(7판 상품)가
    /// <b>4장의 유일한 수집품</b>이라, 받는 순간 «4장을 다 모았다» 가 되어 장이 4로 넘어가고
    /// <c>SceneForChapter(4) == "epilogue"</c> 였다. <b>결승도 안 했는데 결말이 나온다.</b>
    ///
    /// 고치는 기준은 장 번호가 아니라 <b>결승을 깼는가</b>다 — 그건
    /// <see cref="GrandFinal"/> 가 수집 기록과 PlayerPrefs 로만 판단하니 순서에 안 흔들린다.
    ///
    /// <code>
    /// 1~2판 → ch1 · 3~4판 → ch2 · 5~6판 → ch3
    /// 7판   → (없음)            ← 에필로그를 여기서 막는다
    /// 8판   → final_before      ← 증거 여덟 개를 들이민다
    /// 결승 승 → final_after → (다음 방문) epilogue
    /// </code>
    /// </summary>
    public static string CurrentScene()
    {
        // 결승을 깼으면 뒷이야기 → 그 다음 방문에 에필로그.
        if (GrandFinal.Cleared)
            return StoryProgress.HasSeen("final_after") ? "epilogue" : "final_after";

        // 여덟 개를 다 모았고 아직 결승 전이면 «증거를 들이미는» 장면.
        if (GrandFinal.Available) return "final_before";

        // ★ <b>판마다 장면을 둘 수 있다</b>(2026-10-01). 위의 <c>All</c> 에
        //   <c>id = "after3"</c> 같은 장면을 적어 두면 <b>3판을 깬 직후</b>에 나온다.
        //   없으면 아무 일도 안 일어난다 — 쓰고 싶은 판에만 쓰면 된다.
        //   장 단위(두 판에 하나)로는 «한 판 깼는데 아무 말이 없다» 가 생긴다.
        string perRace = $"after{CollectionState.Count}";
        if (!StoryProgress.HasSeen(perRace) && TryFind(perRace, out _)) return perRace;

        string byChapter = SceneForChapter(StoryProgress.CurrentChapter);

        // ★ 결승을 안 깼으면 에필로그는 아직이다. 7판에서 장이 4로 넘어가도 결말이 먼저 나오면 안 된다.
        return byChapter == "epilogue" ? "" : byChapter;
    }

