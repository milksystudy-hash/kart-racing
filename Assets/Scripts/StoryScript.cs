    public static bool TryFind(string sceneId, out Scene scene)
    {
        for (int i = 0; i < All.Length; i++)
            if (All[i].id == sceneId) { scene = All[i]; return true; }

        scene = default;
        return false;
    }

    /// <summary>조건을 통과한 줄만 골라서 순서대로 돌려준다. 이야기가 갈리는 건 여기서 일어난다.</summary>
    public static List<DialogueLine> Playable(string sceneId)
    {
        var result = new List<DialogueLine>();
        if (!TryFind(sceneId, out var scene) || scene.lines == null) return result;

        foreach (var line in scene.lines)
            if (line.Passes) result.Add(line);

        return result;
    }

    public static string TitleOf(string sceneId) =>
        TryFind(sceneId, out var scene) ? scene.title : sceneId;

